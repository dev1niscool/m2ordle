import {readFile, writeFile} from 'node:fs/promises';
import {dirname, join, resolve} from 'node:path';
import {fileURLToPath} from 'node:url';

const PREFIX = '// Generated by scripts/export-classmates.mjs. Public names and IDs only.\nexport const classmates = ';

export function publicClassmates(roster) {
  if (!Array.isArray(roster) || !roster.length) throw new Error('The classmate list must not be empty.');
  const ids = new Set();
  return roster.map(({id, name}) => {
    if (typeof id !== 'string' || !id.trim() || typeof name !== 'string' || !name.trim() || ids.has(id)) {
      throw new Error('Each classmate needs a unique ID and a name.');
    }
    ids.add(id);
    return {id, name};
  });
}

export function renderClassmates(roster) {
  return PREFIX + JSON.stringify(publicClassmates(roster), null, 2) + ';\n';
}

export function parseClassmates(source) {
  if (!source.startsWith(PREFIX) || !source.endsWith(';\n')) throw new Error('Regenerate public/classmates.js with node scripts/export-classmates.mjs.');
  const people = JSON.parse(source.slice(PREFIX.length, -2));
  // Reject extra fields, including table assignments, in the committed public bundle.
  if (renderClassmates(people) !== source) throw new Error('Public classmates must contain only IDs and names. Regenerate the bundle.');
  return people;
}

export async function exportClassmates(root = resolve(dirname(fileURLToPath(import.meta.url)), '..')) {
  const roster = JSON.parse(await readFile(join(root, 'server/roster.json'), 'utf8'));
  await writeFile(join(root, 'public/classmates.js'), renderClassmates(roster));
  return roster.length;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  console.log(`Exported ${await exportClassmates()} public classmate names. Table assignments remain private.`);
}
